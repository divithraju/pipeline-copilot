"""Turn a validated spec into deployable artifacts."""
from .compile import compile_sql
from .spec import Pipeline

_READERS = {"csv": "read_csv", "parquet": "read_parquet", "json": "read_json_auto"}


def python_script(p: Pipeline) -> str:
    reader = _READERS[p.source.format]
    extra = ", header=true" if p.source.format == "csv" else ""
    sql = compile_sql(p)
    return f'''"""Generated by PipelineCopilot: {p.name}
Usage: python {p.name}.py [source_file] [output.parquet]
"""
import sys
import duckdb

SOURCE = sys.argv[1] if len(sys.argv) > 1 else "{p.source.path}"
OUT = sys.argv[2] if len(sys.argv) > 2 else "{p.name}.parquet"
SQL = """
{sql}
"""

con = duckdb.connect()
con.execute("CREATE TABLE src AS SELECT * FROM {reader}(?{extra})", [SOURCE])
con.execute(f"COPY ({{SQL}}) TO '{{OUT}}' (FORMAT PARQUET)")
rows = con.execute(f"SELECT count(*) FROM read_parquet('{{OUT}}')").fetchone()[0]
print(f"wrote {{OUT}}: {{rows}} rows")
'''


def airflow_dag(p: Pipeline) -> str:
    return f'''from datetime import datetime
from airflow import DAG
from airflow.operators.bash import BashOperator

with DAG("{p.name}", start_date=datetime(2026, 1, 1), schedule="@daily", catchup=False) as dag:
    BashOperator(
        task_id="run_{p.name}",
        bash_command="python /opt/pipelines/{p.name}.py {{{{ var.value.source_path }}}} /opt/out/{p.name}.parquet",
    )
'''
